"""Словарь тематического фильтра для постов о балансе Dota 2."""

from collections.abc import Callable, Iterable

from gigarag.patterns import build_any_matcher, word_boundary_pattern

# Регулярные фрагменты терминов патчей и баланса.
BALANCE_TERMS = [
    r"патч", r"нерф", r"понерф", r"баф", r"апнул", r"ап\b", r"ребаланс", r"обновлени",
    r"\b7\.\d\d[a-z]?\b", r"аспект", r"фасет", r"врожд[её]нн", r"талант", r"мет[аеуы]\b",
    r"имб", r"предмет", r"нейтрал", r"патчнот", r"изменени", r"способност", r"ульт",
]

# Русские и сленговые имена героев и предметов, которые в постах встречаются чаще английских.
RU_NAMES = [
    "пудж", "инвокер", "войд", "фейсл", "сф", "шадоу финд", "невермор", "антимаг", "мипо",
    "тинкер", "течис", "пак", "кунка", "акс", "лион", "лина", "зевс", "снайпер", "дровка",
    "морф", "террор", "медуза", "спектра", "фантомка", "пл", "наги", "вайпер", "дазл", "опыт",
    "рики", "слардар", "бист", "бета", "урса", "трент", "брюмастер", "батрайдер",
    "энигма", "марси", "мурлок", "слайс", "джагер", "джаггернаут", "кез", "рингмастер",
    "хускар", "сларк", "тролль", "бристл", "тимбер", "лешрак", "шторм", "эмбер", "земля",
    "аркан", "мидас", "блинк", "бкб", "аганим", "аган", "шард", "рапира", "дагон",
]

# Подписи каналов и название игры: есть почти в каждом посте и для подписей тем бесполезны.
CHANNEL_BOILERPLATE = frozenset({"gabe", "news", "dota", "доты", "доте", "доту", "дота"})


def topic_patterns(entity_names: Iterable[str]) -> list[str]:
    """Термины баланса + русские имена + английские имена из справочников, каждое как отдельное слово."""
    return [
        *BALANCE_TERMS,
        *(word_boundary_pattern(w) for w in RU_NAMES),
        *(word_boundary_pattern(n.lower()) for n in sorted(set(entity_names))),
    ]


def build_topic_matcher(entity_names: Iterable[str]) -> Callable[[str], bool]:
    """Предикат «пост о балансе»: текст содержит хотя бы один термин или имя."""
    return build_any_matcher(topic_patterns(entity_names))
