"""Генерация ответа по найденному контексту: промпт «только по контексту, иначе „Не знаю“» и запрос к LLM.

Промпт и модель фиксированы на всё КТ 5 (`PROMPT_VERSION`). Контекст — топ-5 чанков с префиксом метаданных
(заголовок, тип, патч, дата): номер патча часто есть только в нём, а вопросы gold привязаны к патчам.
Отказ начинается со слов «Не знаю» — так его распознаёт `patterns.is_abstention` без LLM.
"""

from collections.abc import Sequence

from gigarag.enrich import MODEL, SEED, TEMPERATURE
from gigarag.llm import ChatRequest, chat_request

PROMPT_VERSION = 1
CONTEXT_K = 5
THINKING = False  # ответ — абзац текста; скрытое рассуждение deepseek-flash здесь только множит стоимость

SYSTEM = f"""Ты отвечаешь на вопросы игроков Dota 2 о балансе игры. Тебе дадут вопрос и пронумерованные фрагменты
из базы материалов: официальные патчноуты, статьи и комментарии dota2.ru, посты Telegram-каналов.

Правила:
1. Отвечай только на основе фрагментов. Не используй собственные знания об игре, даже если уверен в них:
   числа, патчи, названия и выводы — только те, что есть во фрагментах.
2. Если во фрагментах нет ответа на вопрос — ответь ровно «Не знаю: в найденных материалах нет ответа.»
   и больше ничего не добавляй. Так же отвечай, если фрагменты про другую сущность или другой патч, чем
   в вопросе: правка того же героя в другом патче ответом не является.
3. Если ответ есть только на часть вопроса — ответь на эту часть и прямо скажи, какой части во фрагментах нет.
4. Если в вопросе несколько частей или фрагменты дополняют друг друга — используй все фрагменты, относящиеся
   к вопросу, а не только первый.
5. Отвечай по-русски, кратко и по существу; названия героев, предметов и способностей — как во фрагментах.
   После каждого утверждения укажи номер фрагмента в квадратных скобках, например [2].
(версия промпта {PROMPT_VERSION})"""


def context_block(passages: Sequence[str]) -> str:
    """Пронумерованные фрагменты контекста: [1] … [k]."""
    return "\n\n".join(f"[{n}]\n{text}" for n, text in enumerate(passages, 1))


def answer_user(question: str, passages: Sequence[str]) -> str:
    return f"Вопрос: {question}\n\nФрагменты:\n\n{context_block(passages)}"


def answer_request(question: str, passages: Sequence[str]) -> ChatRequest:
    return chat_request(MODEL, SYSTEM, answer_user(question, passages), TEMPERATURE, SEED, thinking=THINKING)
