def generator_user(qtype: str, documents: list[tuple[str, str]]) -> str:
    docs = "\n\n".join(f"[{doc_id}]\n{text}" for doc_id, text in documents)
    return f"{TYPE_INSTRUCTIONS[qtype]}\n\nДокументы:\n\n{docs}"


def negative_user(kind: str, examples: list[str]) -> str:
    shown = "\n".join(f"- {e}" for e in examples)
    return (f"{NEGATIVE_KINDS[kind]}\n\nДля ориентира по стилю — несколько фрагментов корпуса "
            f"(вопрос НЕ должен опираться на них):\n{shown}")


def style_user(style: str, question: str) -> str:
    return f"Стиль: {STYLE_INSTRUCTIONS[style]}\n\nВопрос: {question}"


def judge_user(question: str, answer: str, passage: str) -> str:
    return f"Вопрос: {question}\nЭталонный ответ: {answer}\n\nОтрывок:\n{passage}"
